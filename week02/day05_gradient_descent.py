"""Week 2 / Day 5: train a linear model with gradient descent."""

import numpy as np


def predict(xs, weight, bias):
    """Return linear predictions for all inputs."""
    return weight * xs + bias


def mean_squared_error(predictions, targets):
    """Return mean squared error."""
    if predictions.shape != targets.shape:
        raise ValueError("predictions 和 targets 的 shape 必须相同")

    return float(np.mean((predictions - targets) ** 2))


def compute_gradients(xs, targets, weight, bias):
    """Return the MSE gradients for weight and bias."""
    predictions = predict(xs, weight, bias)
    errors = predictions - targets

    grad_weight = 2 * np.mean(errors * xs)
    grad_bias = 2 * np.mean(errors)
    return float(grad_weight), float(grad_bias)


def train_linear_regression(xs, targets, learning_rate, epochs, log_every=None):
    """Train weight and bias using full-batch gradient descent."""
    weight = 0.0
    bias = 0.0

    for epoch in range(epochs):
        predictions = predict(xs, weight, bias)
        loss = mean_squared_error(predictions, targets)
        grad_weight, grad_bias = compute_gradients(xs, targets, weight, bias)

        weight -= learning_rate * grad_weight
        bias -= learning_rate * grad_bias

        if log_every is not None and epoch % log_every == 0:
            print(
                f"epoch={epoch:4d} loss={loss:.6f} "
                f"weight={weight:.4f} bias={bias:.4f}"
            )

    final_predictions = predict(xs, weight, bias)
    final_loss = mean_squared_error(final_predictions, targets)
    return weight, bias, final_loss


def demo_one_update():
    """Show the values before and after one gradient-descent step."""
    xs = np.array([0, 1, 2], dtype=np.float32)
    targets = np.array([1, 3, 5], dtype=np.float32)
    weight = 0.0
    bias = 0.0
    learning_rate = 0.1

    predictions_before = predict(xs, weight, bias)
    loss_before = mean_squared_error(predictions_before, targets)
    grad_weight, grad_bias = compute_gradients(xs, targets, weight, bias)

    weight -= learning_rate * grad_weight
    bias -= learning_rate * grad_bias

    predictions_after = predict(xs, weight, bias)
    loss_after = mean_squared_error(predictions_after, targets)

    print("grad_weight:", grad_weight)
    print("grad_bias:", grad_bias)
    print("更新前 loss:", loss_before)
    print("更新后 weight, bias:", weight, bias)
    print("更新后 loss:", loss_after)


def demo_training():
    """Train on data generated by y = 2x + 1."""
    xs = np.array([-2, -1, 0, 1, 2], dtype=np.float32)
    targets = 2 * xs + 1

    weight, bias, loss = train_linear_regression(
        xs,
        targets,
        learning_rate=0.1,
        epochs=100,
        log_every=20,
    )

    print("final weight:", weight)
    print("final bias:", bias)
    print("final loss:", loss)


def practice_gradient_direction():
    """练习 1：观察梯度符号与参数更新方向。"""
    xs = np.array([0, 1, 2], dtype=np.float32)
    targets = np.array([1, 3, 5], dtype=np.float32)
    weight = 0.0
    bias = 0.0

    # TODO:
    # 1. 调用 compute_gradients() 并打印两个梯度。
    grad_weight, grad_bias = compute_gradients(xs, targets, weight, bias)
    print("grad_weight:", grad_weight)
    print("grad_bias:", grad_bias)

    # 2. 判断两个梯度是正数还是负数。
    print("grad_weight > 0?", grad_weight > 0)
    print("grad_bias > 0?", grad_bias > 0)

    # 3. 根据 parameter -= learning_rate * gradient，说明参数会增大还是减小。
    lr = 0.1
    new_weight = weight - lr * grad_weight
    new_bias = bias - lr * grad_bias
    # 梯度是正数，weight -= lr*正数 → weight变大
    print("更新后 weight =", new_weight)
    print("更新后 bias =", new_bias)






